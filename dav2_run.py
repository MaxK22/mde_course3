def predict1_torch(depth, lr_depth):
    # depth: [H, W], lr_depth: [H_lr, W_lr]
    # Resize depth to match lr_depth target size
    pred_resized = F.interpolate(depth.unsqueeze(0).unsqueeze(0),
                                 size=lr_depth.shape,
                                 mode='bilinear',
                                 align_corners=False).squeeze()

    x = pred_resized.flatten()
    y = lr_depth.flatten()

    # Create Design Matrix [x, 1]
    A = torch.stack([x, torch.ones_like(x)], dim=1)

    # Solve least squares: Ax = y
    # result[0] contains [s, t]
    sol = torch.linalg.lstsq(A, y).solution
    s, t = sol[0], sol[1]

    return s * depth + t

def predict2_torch(depth, lr_depth):
    max_depth = lr_depth.max()
    pred_resized = F.interpolate(depth.unsqueeze(0).unsqueeze(0),
                                 size=lr_depth.shape,
                                 mode='bilinear',
                                 align_corners=False).squeeze()

    x = pred_resized.flatten()
    y = 1.0 / lr_depth.flatten()

    A = torch.stack([x, torch.ones_like(x)], dim=1)
    sol = torch.linalg.lstsq(A, y).solution
    s, t = sol[0], sol[1]

    d = s * depth + t
    # Safe reciprocal to avoid div by zero
    metric_map = torch.where(d != 0, 1.0 / d, max_depth)
    return metric_map

def predict3_torch(depth, lr_depth):
    max_depth = lr_depth.max()
    lr_d = 1.0 / lr_depth

    # Center depth by median
    depth_centered = depth - torch.median(depth)

    # Center target inverse depth by median
    t = torch.median(lr_d)
    lr_d_centered = lr_d - t

    # Scale alignment using Mean Absolute Deviation
    depth_scale = torch.mean(torch.abs(depth_centered))
    lr_d_scale = torch.mean(torch.abs(lr_d_centered))

    s = lr_d_scale / (depth_scale + 1e-8) # avoid div by zero

    d = (s * depth_centered + t)
    metric_map = torch.where(d != 0, 1.0 / d, max_depth)
    return metric_map

