def eval_depth(pred, target):
    assert pred.shape == target.shape

    mask = target != 0

    thresh = torch.max((target[mask] / pred[mask] ), (pred[mask]  / target[mask] ))

    d1 = (thresh < 1.25).float().mean()
    d2 = (thresh < 1.25**2).float().mean()
    d3 = (thresh < 1.25**3).float().mean()

    diff = pred[mask]  - target[mask]

    pred_safe = torch.clamp(pred[mask], min=1e-3)
    target_safe = torch.clamp(target[mask], min=1e-3)
    diff_log = torch.log(pred_safe) - torch.log(target_safe)

    # diff_log = torch.log(pred[mask]) - torch.log(target[mask])

    abs_rel = torch.mean(torch.abs(diff) / target[mask])

    rmse = torch.sqrt(torch.mean(torch.pow(diff, 2)))
    mae = torch.mean(torch.abs(diff))

    silog = torch.sqrt(torch.pow(diff_log, 2).mean() - 0.5 * torch.pow(diff_log.mean(), 2))

    return {
        'd1': d1.item(),
        'd2': d2.item(),
        'd3': d3.item(),
        'abs_rel': abs_rel.item(),
        'rmse': rmse.item(),
        'mae': mae.item(),
        'silog': silog.item()
    }
