def predict_(depth, lr_depth):
    target_h, target_w = depth.shape[-2:]
    # 2. Reshape to 4D: [Batch=1, Channel=1, H_lr, W_lr]
    lr_depth_4d = lr_depth.unsqueeze(0).unsqueeze(0)
    interpolated_depth = F.interpolate(
        lr_depth_4d,
        size=(target_h, target_w),
        mode='bilinear',
        align_corners=False
    ).squeeze()
    return interpolated_depth

